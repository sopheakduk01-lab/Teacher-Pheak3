 ក. ដើម្បីឱ្យមនុស្សមានសិទ្ធិកាប់ឈើតាមចិត្ត
 ខ. ដើម្បីទុកដីឱ្យនៅទំនេរគ្មានការអភិវឌ្ឍអ្វី
 គ. ដើម្បីបង្កើនការទាញយកធនធានឱ្យអស់ពីដី
 ឃ. ដើម្បីរក្សាជីវិតលើផែនដីឱ្យនៅគង់វង្សយូរអង្វែង  (ចម្លើយត្រឹមត្រូវ)
