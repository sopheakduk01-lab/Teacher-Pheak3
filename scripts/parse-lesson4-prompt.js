const clean = t => t.replace(/\s*\([^)]*\)/g, '').trim();

const lines = rawText.split('\n');
const parsed = [];
let curQ = null;

lines.forEach(line => {
  const trimmed = line.trim();
  if (!trimmed) return;
  if (trimmed.startsWith('សំណួរទី')) {
    if (curQ) parsed.push(curQ);
    curQ = {
      q: clean(trimmed.replace(/^សំណួរទី\s*\d+\s*៖\s*/, '')),
      opts: [],
      h: "គិតអំពីនិយមន័យ និងការថែរក្សាបរិស្ថានធម្មជាតិ"
    };
  } else if (curQ) {
    const isCorrect = trimmed.includes("ចម្លើយត្រឹមត្រូវ");
    const textOnly = clean(trimmed.replace(/^[កខគឃ]\.\s*/, '').replace("ចម្លើយត្រឹមត្រូវ", ""));
    curQ.opts.push({ t: textOnly, c: isCorrect });
  }
});
if (curQ) parsed.push(curQ);

console.log("Parsed questions count:", parsed.length);

// Count original correct positions
const counts = [0, 0, 0, 0];
parsed.forEach((item, idx) => {
  if (item.opts.length !== 4) {
    console.error(`Question ${idx + 1} has ${item.opts.length} options!`);
  }
  const cIdx = item.opts.findIndex(o => o.c);
  if (cIdx !== -1) counts[cIdx]++;
  else console.error(`Question ${idx + 1} has NO correct answer!`);
});
console.log("Raw correct answer counts:", counts);

// Now rebalance so that correct answer position rotates evenly: 0 (A), 1 (B), 2 (C), 3 (D)
// exactly 10 questions each!
const rebalanced = parsed.map((item, qIdx) => {
  const targetCorrectIdx = qIdx % 4; // 0=A, 1=B, 2=C, 3=D

  const origCorrectOpt = item.opts.find(o => o.c);
  const origWrongOpts = item.opts.filter(o => !o.c);

  const newOpts = new Array(4);
  newOpts[targetCorrectIdx] = {
    t: clean(origCorrectOpt.t),
    c: true,
    e: "ចម្លើយត្រឹមត្រូវតាមខ្លឹមសារសៀវភៅពុម្ពវិទ្យាសាស្ត្រ ថ្នាក់ទី ៦ ជំពូកទី ២ មេរៀនទី ៤ បរិស្ថានធម្មជាតិ។"
  };

  let wrongPtr = 0;
  for (let i = 0; i < 4; i++) {
    if (i !== targetCorrectIdx) {
      const wrong = origWrongOpts[wrongPtr++];
      newOpts[i] = {
        t: clean(wrong.t),
        c: false,
        e: "ចម្លើយនេះមិនទាន់ត្រឹមត្រូវតាមគោលការណ៍វិទ្យាសាស្ត្របរិស្ថានឡើយ។"
      };
    }
  }

  return {
    q: clean(item.q),
    opts: newOpts,
    h: "គិតអំពីនិយមន័យ និងការថែរក្សាបរិស្ថានធម្មជាតិ"
  };
});

// Verify distribution
const finalCounts = [0, 0, 0, 0];
rebalanced.forEach(q => {
  const cIdx = q.opts.findIndex(o => o.c);
  finalCounts[cIdx]++;
});
console.log("Final rebalanced Lesson 4 distribution (A, B, C, D):", finalCounts);

fs.writeFileSync('scripts/lesson4_questions.json', JSON.stringify(rebalanced, null, 2));
console.log("Saved scripts/lesson4_questions.json successfully!");
